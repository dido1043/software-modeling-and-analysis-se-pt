/* =============================================================================
   HBO Max - Software Modeling and Analysis course work
   File:    11_dw_dimensions.sql
   Purpose: 10 Kimball dimensions, matching the UML physical model in
            docs/diagrams/03-dw-physical-uml.drawio.
   Target:  Microsoft SQL Server 2019+
   Depends: 10_create_dw_database.sql must have run first.

   Modelling conventions
     - Every dimension has an integer surrogate key named "<Name>Key" and the
       natural key preserved as "<Name>ID" with a UNIQUE constraint.
     - Every dimension carries a "-1 Unknown" member seeded at the bottom of
       the file. Fact loaders fall back to -1 when a lookup fails, so a fact
       row is never dropped.
     - RowInsertedAt / RowUpdatedAt audit columns are maintained by the ETL.
     - SCD Type 2 is applied to DimPlan (price changes) and DimSubscriber
       (geography, name, tenure band). Those two dimensions have
       RowEffectiveFrom / RowEffectiveTo / IsCurrent / RowVersion.
   ============================================================================= */

USE HBOMaxDW;
GO

/* =============================================================================
   dw.DimDate - calendar generated by etl.usp_LoadDimDate
   ============================================================================= */
CREATE TABLE dw.DimDate
(
    DateKey              INT         NOT NULL,
    FullDate             DATE        NOT NULL,
    DayNumberOfMonth     TINYINT     NULL,
    DayNumberOfYear      SMALLINT    NULL,
    DayNumberOfWeek      TINYINT     NULL,
    DayName              VARCHAR(9)  NOT NULL,
    DayNameShort         VARCHAR(3)  NOT NULL,
    IsWeekend            BIT         NOT NULL,
    IsHoliday            BIT         NOT NULL,
    HolidayName          VARCHAR(40) NULL,
    IsoWeekOfYear        TINYINT     NULL,
    IsoYear              SMALLINT    NULL,
    MonthNumber          TINYINT     NULL,
    MonthName            VARCHAR(9)  NOT NULL,
    MonthNameShort       VARCHAR(3)  NOT NULL,
    MonthKey             INT         NULL,
    MonthYearLabel       VARCHAR(8)  NOT NULL,
    MonthStartDate       DATE        NULL,
    MonthEndDate         DATE        NULL,
    IsLastDayOfMonth     BIT         NOT NULL,
    DaysInMonth          TINYINT     NULL,
    QuarterNumber        TINYINT     NULL,
    QuarterName          VARCHAR(2)  NOT NULL,
    QuarterYearLabel     VARCHAR(8)  NOT NULL,
    YearNumber           SMALLINT    NULL,
    FiscalYear           SMALLINT    NULL,
    FiscalQuarter        TINYINT     NULL,
    FiscalMonthNumber    TINYINT     NULL,
    FiscalYearLabel      VARCHAR(8)  NOT NULL,
    RelativeDayOffset    AS CAST(DATEDIFF(DAY,   CAST(SYSUTCDATETIME() AS DATE), FullDate) AS INT),
    RelativeMonthOffset  AS CAST(DATEDIFF(MONTH, CAST(SYSUTCDATETIME() AS DATE), FullDate) AS INT),
    RelativeYearOffset   AS CAST(DATEDIFF(YEAR,  CAST(SYSUTCDATETIME() AS DATE), FullDate) AS INT),
    RowInsertedAt        DATETIME2(3) NOT NULL CONSTRAINT DF_DimDate_Ins DEFAULT (SYSUTCDATETIME()),
    RowUpdatedAt         DATETIME2(3) NOT NULL CONSTRAINT DF_DimDate_Upd DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_DimDate         PRIMARY KEY (DateKey),
    CONSTRAINT UQ_DimDate_Full    UNIQUE (FullDate)
);
GO
-- -1 Unknown member: facts point here when a date is missing or falls outside
-- the generated calendar (e.g. an open-ended licence has no AvailableUntil).
