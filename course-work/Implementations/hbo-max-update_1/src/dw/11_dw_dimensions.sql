/* =============================================================================
   dw.DimPlan - SCD Type 2 on price band and plan metadata
   ============================================================================= */
CREATE TABLE dw.DimPlan
(
    PlanKey                           INT            NOT NULL IDENTITY(1,1),
    PlanID                            INT            NOT NULL,
    PlanCode                          VARCHAR(20)    NOT NULL,
    PlanName                          NVARCHAR(60)   NOT NULL,
    MonthlyPrice                      DECIMAL(8,2)   NOT NULL,
    AnnualPrice                       DECIMAL(8,2)   NULL,
    EffectiveMonthlyPriceFromAnnual   AS CAST(
        CASE WHEN AnnualPrice IS NULL THEN MonthlyPrice
             ELSE AnnualPrice / 12.0 END AS DECIMAL(10,4)) PERSISTED,
    CurrencyCode                      CHAR(3)        NOT NULL,
    PriceBand                         VARCHAR(20)    NOT NULL,
    MaxConcurrentStreams              TINYINT        NOT NULL,
    MaxVideoQuality                   VARCHAR(4)     NOT NULL,
    MaxProfiles                       TINYINT        NOT NULL,
    AllowsDownloads                   BIT            NOT NULL,
    HasAdvertising                    BIT            NOT NULL,
    AdvertisingLabel                  VARCHAR(12)    NOT NULL,
    IsActive                          BIT            NOT NULL,
    SourceEffectiveFrom               DATE           NULL,
    RowEffectiveFrom                  DATE           NOT NULL,
    RowEffectiveTo                    DATE           NOT NULL CONSTRAINT DF_DimPlan_To DEFAULT ('9999-12-31'),
    IsCurrent                         BIT            NOT NULL CONSTRAINT DF_DimPlan_Curr DEFAULT (1),
    RowVersion                        INT            NOT NULL CONSTRAINT DF_DimPlan_Ver  DEFAULT (1),
    RowInsertedAt                     DATETIME2(3)   NOT NULL CONSTRAINT DF_DimPlan_Ins  DEFAULT (SYSUTCDATETIME()),
    RowUpdatedAt                      DATETIME2(3)   NOT NULL CONSTRAINT DF_DimPlan_Upd  DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_DimPlan         PRIMARY KEY (PlanKey),
    CONSTRAINT UQ_DimPlan_Scd     UNIQUE (PlanID, RowEffectiveFrom)
);
GO
CREATE INDEX IX_DimPlan_Current ON dw.DimPlan (PlanID) WHERE IsCurrent = 1;
GO
